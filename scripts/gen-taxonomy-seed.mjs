#!/usr/bin/env node
/**
 * P04 · Generate supabase/seed/*.sql from content/taxonomy/csec_2027_taxonomy_seed.json
 *
 * Expected JSON shape (see TECHNICAL_BUILD_SPEC.md §3.3):
 * {
 *   "subject": { "code", "name", "is_active?", "sequence?" },
 *   "syllabus": { "code", "official_code?", "effective_from_year", "effective_from_month",
 *                 "has_modules?", "is_default?", "source_document?" },
 *   "modules": [{
 *     "module_no", "name", "paper01_items?", "paper02_marks?", "weighted_marks?", "duration_hours?",
 *     "topics": [{
 *       "topic_no", "code", "name", "sequence", "paper01_items?", "paper02_marks_group?", "paper02_marks?",
 *       "objectives": [{
 *         "code", "objective_no", "statement", "content_notes?", "needs_human_review?", "sequence?"
 *       }]
 *     }]
 *   }],
 *   "skills"?: [{ "code", "name", "description?", "is_active?" }],
 *   "skill_prerequisites"?: [{ "skill_code", "prerequisite_skill_code" }],
 *   "skill_objectives"?: [{ "skill_code", "objective_code" }]
 * }
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const SEED_JSON = join(ROOT, "content/taxonomy/csec_2027_taxonomy_seed.json");
const OUT_DIR = join(ROOT, "supabase/seed");

function sqlLiteral(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value, fallback = false) {
  const v = value ?? fallback;
  return v ? "true" : "false";
}

function loadSeed() {
  let raw;
  try {
    raw = readFileSync(SEED_JSON, "utf8");
  } catch {
    console.error(`Missing seed file: ${SEED_JSON}`);
    console.error(
      "Add content/taxonomy/csec_2027_taxonomy_seed.json or run scripts/extract-syllabus.py against the official PDF.",
    );
    process.exit(1);
  }
  return JSON.parse(raw);
}

function writeFile(name, body) {
  const path = join(OUT_DIR, name);
  writeFileSync(path, `${body.trim()}\n`, "utf8");
  console.log(`wrote ${path}`);
}

function generate() {
  const data = loadSeed();
  mkdirSync(OUT_DIR, { recursive: true });

  const subject = data.subject ?? {};
  const syllabus = data.syllabus ?? {};
  const modules = data.modules ?? [];

  const subjectCode = subject.code ?? "CSEC_MATH";
  const syllabusCode = syllabus.code ?? "V2027";

  const lines01 = [
    "-- Generated by scripts/gen-taxonomy-seed.js — do not edit by hand",
    "begin;",
    "",
    `insert into public.subjects (code, name, is_active, sequence) values (`,
    `  ${sqlLiteral(subjectCode)},`,
    `  ${sqlLiteral(subject.name ?? "CSEC Mathematics")},`,
    `  ${sqlBool(subject.is_active, true)},`,
    `  ${subject.sequence ?? 0}`,
    `) on conflict (code) do update set`,
    `  name = excluded.name,`,
    `  is_active = excluded.is_active,`,
    `  sequence = excluded.sequence;`,
    "",
    `insert into public.syllabus_versions (`,
    `  code, subject_code, official_code, effective_from_year, effective_from_month,`,
    `  has_modules, is_default, source_document`,
    `) values (`,
    `  ${sqlLiteral(syllabusCode)}::public.syllabus_code,`,
    `  ${sqlLiteral(subjectCode)},`,
    `  ${sqlLiteral(syllabus.official_code ?? "CXC 05/G/SYLL 16")},`,
    `  ${syllabus.effective_from_year ?? 2027},`,
    `  ${sqlLiteral(syllabus.effective_from_month ?? "may_june")}::public.sitting_month,`,
    `  ${sqlBool(syllabus.has_modules, true)},`,
    `  ${sqlBool(syllabus.is_default, true)},`,
    `  ${sqlLiteral(syllabus.source_document ?? "CSEC_Mathematics_Syllabus_2027.pdf")}`,
    `) on conflict (code) do update set`,
    `  subject_code = excluded.subject_code,`,
    `  official_code = excluded.official_code,`,
    `  effective_from_year = excluded.effective_from_year,`,
    `  effective_from_month = excluded.effective_from_month,`,
    `  has_modules = excluded.has_modules,`,
    `  is_default = excluded.is_default,`,
    `  source_document = excluded.source_document;`,
    "",
  ];

  for (const mod of modules) {
    lines01.push(
      `insert into public.modules (`,
      `  syllabus_code, module_no, name, paper01_items, paper02_marks, weighted_marks, duration_hours`,
      `) values (`,
      `  ${sqlLiteral(syllabusCode)}::public.syllabus_code,`,
      `  ${mod.module_no},`,
      `  ${sqlLiteral(mod.name)},`,
      `  ${mod.paper01_items ?? 20},`,
      `  ${mod.paper02_marks ?? 30},`,
      `  ${mod.weighted_marks ?? 100},`,
      `  ${mod.duration_hours ?? 65}`,
      `) on conflict (syllabus_code, module_no) do update set`,
      `  name = excluded.name,`,
      `  paper01_items = excluded.paper01_items,`,
      `  paper02_marks = excluded.paper02_marks,`,
      `  weighted_marks = excluded.weighted_marks,`,
      `  duration_hours = excluded.duration_hours;`,
      "",
    );
  }

  lines01.push("commit;");
  writeFile("01_syllabus_v2027.sql", lines01.join("\n"));

  const lines02 = [
    "-- Generated by scripts/gen-taxonomy-seed.js — do not edit by hand",
    "begin;",
    "",
  ];

  for (const mod of modules) {
    for (const topic of mod.topics ?? []) {
      lines02.push(
        `insert into public.topics (`,
        `  syllabus_code, module_id, topic_no, code, name, sequence,`,
        `  paper01_items, paper02_marks_group, paper02_marks, is_active`,
        `)`,
        `select`,
        `  ${sqlLiteral(syllabusCode)}::public.syllabus_code,`,
        `  m.id,`,
        `  ${topic.topic_no},`,
        `  ${sqlLiteral(topic.code)},`,
        `  ${sqlLiteral(topic.name)},`,
        `  ${topic.sequence},`,
        `  ${topic.paper01_items ?? "null"},`,
        `  ${topic.paper02_marks_group ? sqlLiteral(topic.paper02_marks_group) : "null"},`,
        `  ${topic.paper02_marks ?? "null"},`,
        `  ${sqlBool(topic.is_active, true)}`,
        `from public.modules m`,
        `where m.syllabus_code = ${sqlLiteral(syllabusCode)}::public.syllabus_code`,
        `  and m.module_no = ${mod.module_no}`,
        `on conflict (syllabus_code, code) do update set`,
        `  module_id = excluded.module_id,`,
        `  topic_no = excluded.topic_no,`,
        `  name = excluded.name,`,
        `  sequence = excluded.sequence,`,
        `  paper01_items = excluded.paper01_items,`,
        `  paper02_marks_group = excluded.paper02_marks_group,`,
        `  paper02_marks = excluded.paper02_marks,`,
        `  is_active = excluded.is_active;`,
        "",
      );
    }
  }

  lines02.push("commit;");
  writeFile("02_topics.sql", lines02.join("\n"));

  const lines03 = [
    "-- Generated by scripts/gen-taxonomy-seed.js — do not edit by hand",
    "begin;",
    "",
  ];

  for (const mod of modules) {
    for (const topic of mod.topics ?? []) {
      for (const obj of topic.objectives ?? []) {
        lines03.push(
          `insert into public.specific_objectives (`,
          `  syllabus_code, topic_id, code, objective_no, statement, content_notes,`,
          `  needs_human_review, sequence, is_active`,
          `)`,
          `select`,
          `  ${sqlLiteral(syllabusCode)}::public.syllabus_code,`,
          `  t.id,`,
          `  ${sqlLiteral(obj.code)},`,
          `  ${obj.objective_no},`,
          `  ${sqlLiteral(obj.statement)},`,
          `  ${obj.content_notes ? sqlLiteral(obj.content_notes) : "null"},`,
          `  ${sqlBool(obj.needs_human_review, false)},`,
          `  ${obj.sequence ?? 0},`,
          `  ${sqlBool(obj.is_active, true)}`,
          `from public.topics t`,
          `where t.syllabus_code = ${sqlLiteral(syllabusCode)}::public.syllabus_code`,
          `  and t.code = ${sqlLiteral(topic.code)}`,
          `on conflict (syllabus_code, code) do update set`,
          `  topic_id = excluded.topic_id,`,
          `  objective_no = excluded.objective_no,`,
          `  statement = excluded.statement,`,
          `  content_notes = excluded.content_notes,`,
          `  needs_human_review = excluded.needs_human_review,`,
          `  sequence = excluded.sequence,`,
          `  is_active = excluded.is_active;`,
          "",
        );
      }
    }
  }

  lines03.push("commit;");
  writeFile("03_specific_objectives.sql", lines03.join("\n"));

  const skills = data.skills ?? [];
  const lines04 = [
    "-- Generated by scripts/gen-taxonomy-seed.js — do not edit by hand",
    "begin;",
    "",
  ];

  for (const skill of skills) {
    lines04.push(
      `insert into public.skills (code, name, description, is_active) values (`,
      `  ${sqlLiteral(skill.code)},`,
      `  ${sqlLiteral(skill.name)},`,
      `  ${skill.description ? sqlLiteral(skill.description) : "null"},`,
      `  ${sqlBool(skill.is_active, true)}`,
      `) on conflict (code) do update set`,
      `  name = excluded.name,`,
      `  description = excluded.description,`,
      `  is_active = excluded.is_active;`,
      "",
    );
  }

  for (const edge of data.skill_prerequisites ?? []) {
    lines04.push(
      `insert into public.skill_prerequisites (skill_id, prerequisite_skill_id)`,
      `select s.id, p.id`,
      `from public.skills s`,
      `join public.skills p on p.code = ${sqlLiteral(edge.prerequisite_skill_code)}`,
      `where s.code = ${sqlLiteral(edge.skill_code)}`,
      `on conflict do nothing;`,
      "",
    );
  }

  for (const link of data.skill_objectives ?? []) {
    lines04.push(
      `insert into public.skill_objectives (skill_id, specific_objective_id)`,
      `select sk.id, so.id`,
      `from public.skills sk`,
      `join public.specific_objectives so`,
      `  on so.code = ${sqlLiteral(link.objective_code)}`,
      ` and so.syllabus_code = ${sqlLiteral(syllabusCode)}::public.syllabus_code`,
      `where sk.code = ${sqlLiteral(link.skill_code)}`,
      `on conflict do nothing;`,
      "",
    );
  }

  lines04.push("commit;");
  writeFile("04_skills.sql", lines04.join("\n"));

  const objectiveCount = modules.reduce(
    (sum, mod) =>
      sum +
      (mod.topics ?? []).reduce((tSum, topic) => tSum + (topic.objectives ?? []).length, 0),
    0,
  );
  const topicCount = modules.reduce((sum, mod) => sum + (mod.topics ?? []).length, 0);

  console.log(
    `Generated seed for ${modules.length} modules, ${topicCount} topics, ${objectiveCount} objectives.`,
  );

  const flagged = modules.flatMap((mod) =>
    (mod.topics ?? []).flatMap((topic) =>
      (topic.objectives ?? []).filter((o) => o.needs_human_review),
    ),
  );
  if (flagged.length > 0) {
    console.warn(
      `Warning: ${flagged.length} objectives still flagged needs_human_review — must be cleared before P05.`,
    );
  }
}

generate();
